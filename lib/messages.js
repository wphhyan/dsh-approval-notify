/** Plain-text table for one language. */
export function texts(language) {
  return language === 'en' ? en : zh
}

/** Settings-page table for one language. */
export function clientTexts(language) {
  return language === 'en' ? clientEn : clientZh
}

/** Dictionaries registered with the client locale service. */
export const CLIENT_DICTIONARIES = { zh: clientZh, en: clientEn }

/**
 * Replace `{name}` placeholders in one template.
 * @param {string} template - message template.
 * @param {Record<string, unknown>} [variables] - replacement values.
 * @returns {string} filled text.
 */
export function fmt(template, variables = {}) {
  return String(template ?? '').replace(/\{([a-zA-Z]+)\}/gu, (match, key) =>
    (key in variables ? String(variables[key]) : match))
}